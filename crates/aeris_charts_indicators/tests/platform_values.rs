//! The verified 通达信-style indicator rules, pinned on a deterministic synthetic daily series.
//!
//! Rule sources: 通达信's official formula help, https://help.tdx.com.cn/gspt/ (the page
//! "通达信指标公式算法释疑" and its function reference: `EMA`, `SMA(X,N,M)` started at its first
//! input, `HHV`/`LLV` over the bars available).
//! 这些规则于 2026-09-28 与公开提供方基于真实 A 股柱的服务端计算值交叉验证；
//! 该数据不提交到仓库，证据摘要见 `docs/api/indicators.md`。本文件固定以下规则：
//!
//! - MACD(12,26,9), China convention: `EMA(X,N)` is `Y = (2X + (N-1)Y') / (N+1)` started at
//!   `Y0 = X0`, `DIF = EMA(C,12) - EMA(C,26)`, `DEA = EMA(DIF,9)` (so DIF = DEA = 0 on the first
//!   row), histogram `(DIF-DEA)*2`. Exact from the first row.
//! - BOLL(20,2): `MA(C,20) ± 2σ` with the population σ (divide by N). Exact from row 19.
//! - KDJ(9,3,3), 通达信 "KDJ普通版": `RSV = (C - LLV(L,9)) / (HHV(H,9) - LLV(L,9)) * 100`, with
//!   `HHV`/`LLV` over the rows available while fewer than 9 exist, `K = SMA(RSV,3,1)`,
//!   `D = SMA(K,3,1)` started at their first input, `J = 3K - 2D` (not clipped). The
//!   `first_value` seed reproduces it from row 0; the textbook `fifty` start converges to it after
//!   the warm-up query's `convergence_rows`.
//!
//! The 132 sessions are synthetic, generated from a seeded formula: a wide-range first session, a
//! slide, a six-session flat stretch (open = high = low = close) shorter than the KDJ period, a gap
//! up whose low clears the previous high (row 78), and a gap down whose high stays below the
//! previous low (row 104). Every RSV window keeps a range, because platforms disagree on
//! `HHV == LLV` and this file pins only verified rules. A standalone script that implements the
//! rules above directly, without this crate, computed the expected columns, embedded to 10 decimal
//! places.
//!
//! Each row is `[high, low, close, K, D, J, DIF, DEA, MACD, MID, UB, LB]`; `NAN` marks a row where
//! the rule has no value yet.

use aeris_charts_indicators::{
    IncrementalState, IndicatorInput, IndicatorSeed, KdjSeed, bollinger, kdj_with_seed, macd_with,
};

const NAN: f64 = f64::NAN;

type Row = [f64; 12];

const HIGH: usize = 0;
const LOW: usize = 1;
const CLOSE: usize = 2;
const K: usize = 3;
const D: usize = 4;
const J: usize = 5;
const DIF: usize = 6;
const DEA: usize = 7;
const MACD: usize = 8;
const MID: usize = 9;
const UB: usize = 10;
const LB: usize = 11;

/// The embedded literals' rounding (5e-11) with headroom for evaluation order.
const EXACT: f64 = 1e-9;

fn column(index: usize) -> Vec<f64> {
    ROWS.iter().map(|row| row[index]).collect()
}

/// Full-rebuild outputs of an incremental runtime over `ROWS`, NaN before `output_from`.
fn runtime(mut state: IncrementalState) -> Vec<Vec<f64>> {
    let (high, low, close) = (column(HIGH), column(LOW), column(CLOSE));
    let times = (0..ROWS.len() as i64).collect::<Vec<_>>();
    state.rebuild_from(
        IndicatorInput {
            times: &times,
            open: &close,
            high: &high,
            low: &low,
            close: &close,
            volume: &[],
            amount: &[],
        },
        0,
    );
    (0..state.output_count())
        .map(|output| {
            let mut values = vec![NAN; state.output_from(output)];
            values.extend_from_slice(state.output(output));
            values
        })
        .collect()
}

fn assert_close(label: &str, actual: f64, expected: f64, tolerance: f64) {
    assert!(
        (actual - expected).abs() <= tolerance,
        "{label}: {actual} != expected {expected}"
    );
}

#[test]
fn china_macd_starts_every_ema_at_the_first_value_and_doubles_the_histogram() {
    let closes = column(CLOSE);
    let dense = macd_with(&closes, 12, 26, 9, IndicatorSeed::FirstValue, 2.0);
    let streamed = runtime(IncrementalState::macd_with(
        12,
        26,
        9,
        IndicatorSeed::FirstValue,
        2.0,
    ));
    for (row, expected) in ROWS.iter().enumerate() {
        let point = dense[row];
        let actual = [point.macd, point.signal, point.histogram];
        for (output, index) in [DIF, DEA, MACD].into_iter().enumerate() {
            let label = format!("row {row} MACD output {output}");
            assert_close(&label, actual[output].unwrap(), expected[index], EXACT);
            assert_close(&label, streamed[output][row], expected[index], EXACT);
        }
    }
}

#[test]
fn bollinger_uses_the_population_deviation() {
    let closes = column(CLOSE);
    let dense = bollinger(&closes, 20, 2.0);
    let streamed = runtime(IncrementalState::bollinger(20, 2.0));
    for (row, expected) in ROWS.iter().enumerate() {
        let point = dense[row];
        if expected[MID].is_nan() {
            assert!(row < 19 && point.middle.is_none(), "row {row}");
            assert!(
                streamed.iter().all(|output| output[row].is_nan()),
                "row {row}"
            );
            continue;
        }
        let actual = [point.upper, point.middle, point.lower];
        for (output, index) in [UB, MID, LB].into_iter().enumerate() {
            let label = format!("row {row} BOLL output {output}");
            assert_close(&label, actual[output].unwrap(), expected[index], EXACT);
            assert_close(&label, streamed[output][row], expected[index], EXACT);
        }
    }
}

#[test]
fn first_value_kdj_takes_the_available_window_and_the_textbook_start_converges_to_it() {
    let (high, low, close) = (column(HIGH), column(LOW), column(CLOSE));
    // The RSV each row feeds K, recovered through `SMA(RSV,3,1)`: `RSV_t = 3K_t - 2K_{t-1}`.
    let expected_rsv = |row: usize| 3.0 * ROWS[row][K] - 2.0 * ROWS[row - 1][K];
    for (seed, first_rsv_row) in [(KdjSeed::FirstValue, 1), (KdjSeed::Fifty, 9)] {
        let dense = kdj_with_seed(&high, &low, &close, 9, 3, 3, seed);
        let state = IncrementalState::kdj_with_seed(9, 3, 3, seed);
        let converged = [0, 1, 2].map(|output| state.convergence_rows(output).unwrap());
        let streamed = runtime(state);
        let mut widest_early_gap = 0.0_f64;
        for (row, expected) in ROWS.iter().enumerate() {
            let point = [dense[row].k, dense[row].d, dense[row].j];
            for output in 0..3 {
                let dense = point[output].unwrap_or(NAN);
                let streamed = streamed[output][row];
                assert!(
                    dense.to_bits() == streamed.to_bits() || (dense - streamed).abs() < 1e-9,
                    "row {row} {seed:?} output {output}: {dense} != {streamed}"
                );
            }
            // The RSV window rule, independent of how each seed starts K.
            if row >= first_rsv_row {
                let k = |row: usize| dense[row].k.unwrap();
                assert_close(
                    &format!("row {row} {seed:?} RSV"),
                    3.0 * k(row) - 2.0 * k(row - 1),
                    expected_rsv(row),
                    1e-8,
                );
            }
            // `first_value` is the rule itself, from row 0. `convergence_rows` promises every other
            // start's weight is below 0.1%, which is 0.1 on KDJ's 0-100 scale.
            for (output, index) in [K, D, J].into_iter().enumerate() {
                let (from, tolerance) = match seed {
                    KdjSeed::FirstValue => (0, EXACT),
                    KdjSeed::Fifty => (converged[output], 0.1),
                };
                let label = format!("row {row} {seed:?} KDJ output {output}");
                if row >= from {
                    assert_close(&label, point[output].unwrap(), expected[index], tolerance);
                } else if let Some(actual) = point[output] {
                    widest_early_gap = widest_early_gap.max((actual - expected[index]).abs());
                }
            }
        }
        if seed == KdjSeed::Fifty {
            // The textbook start really differs before convergence, so the check above is not
            // vacuous on this series.
            assert!(widest_early_gap > 1.0, "{widest_early_gap}");
        }
    }
}

